from scipy import stats

def resumen_outliers_zscore(data, variables, umbral=3):
    filas = []
    for v in variables:
        # Calculamos el Z-score para la variable
        z_scores = np.abs(stats.zscore(data[v]))
        n = int((z_scores > umbral).sum())
        filas.append({
            "Variable": v,
            "Outliers (Z > 3)": n,
            "Porcentaje (Z)": round(n / len(data) * 100, 2)
        })
    return pd.DataFrame(filas).sort_values("Outliers (Z > 3)", ascending=False).reset_index(drop=True)

