from xgboost import XGBClassifier

optuna.logging.set_verbosity(optuna.logging.WARNING)
N_TRIALS = 30

def optimizar(sugerir, construir, n_trials=N_TRIALS):
    def objetivo(trial):
        pipe = construir(sugerir(trial))
        return cross_val_score(pipe, X_train, y_train, cv=cv3, scoring="f1_macro", n_jobs=-1).mean()
    estudio = optuna.create_study(direction="maximize", sampler=optuna.samplers.TPESampler(seed=SEED))
    estudio.optimize(objetivo, n_trials=n_trials)
    return estudio

def graficar_optuna(estudio, titulo):
    vals = estudio.trials_dataframe()["value"]
    plt.figure(figsize=(6, 3.5))
    plt.plot(vals, "o", alpha=0.5, label="cada prueba")
    plt.plot(vals.cummax(), "-", label="mejor hasta el momento")
    plt.xlabel("Prueba"); plt.ylabel("F1 macro (CV)"); plt.title(titulo); plt.legend()
    plt.tight_layout(); plt.show()

def sugerir_knn(trial):
    return {"n_neighbors": trial.suggest_int("n_neighbors", 3, 51),
            "weights": trial.suggest_categorical("weights", ["uniform", "distance"]),
            "p": trial.suggest_int("p", 1, 2)}                      # 1 = Manhattan, 2 = Euclídea

def sugerir_xgb(trial):
    return {"n_estimators": trial.suggest_int("n_estimators", 100, 500, step=50),
            "max_depth": trial.suggest_int("max_depth", 2, 10),
            "learning_rate": trial.suggest_float("learning_rate", 0.01, 0.3, log=True),
            "subsample": trial.suggest_float("subsample", 0.5, 1.0),
            "colsample_bytree": trial.suggest_float("colsample_bytree", 0.5, 1.0),
            "min_child_weight": trial.suggest_int("min_child_weight", 1, 10),
            "reg_lambda": trial.suggest_float("reg_lambda", 1e-3, 10.0, log=True)}

def nuevo_xgb(**params):
    return XGBClassifier(random_state=SEED, n_jobs=1, eval_metric="mlogloss", verbosity=0, **params)

def ejecutar_escenario(nombre, excluir):
    print("=" * 70); print("ESCENARIO", nombre); print("=" * 70)

    # ---------- selección de variables (solo entrenamiento)
    cfg = construir_cfg(excluir)
    eliminadas = filtro_correlacion(cfg["num"])
    cfg["num"] = [c for c in cfg["num"] if c not in eliminadas]
    print("Numéricas usadas:", cfg["num"])
    print("Eliminadas por correlación > 0.90:", eliminadas if eliminadas else "ninguna")

    prep = crear_preprocesador(cfg).fit(X_train)
    nombres = [n.split("__", 1)[1] for n in prep.get_feature_names_out()]
    rf_doc = RandomForestClassifier(n_estimators=300, random_state=SEED, n_jobs=-1).fit(prep.transform(X_train), y_train)
    imp = pd.Series(rf_doc.feature_importances_, index=nombres).sort_values()
    imp.tail(12).plot(kind="barh", figsize=(7, 4.5), title=f"Importancia de variables (RF, solo entrenamiento)\n{nombre}")
    plt.tight_layout(); plt.show()

    # ---------- ¿conviene usar SelectFromModel? (se prueban tres configuraciones con validación cruzada)
    rf = lambda: RandomForestClassifier(n_estimators=200, random_state=SEED, n_jobs=-1)
    opciones = {"Sin selección": None,
                "Conservadora (umbral 0.5 x mediana)": "0.5*median",
                "Agresiva (umbral mediana)": "median"}
    filas_sel = []
    for etiqueta, umbral in opciones.items():
        f1_sel, desv_sel = cv_f1(crear_pipeline(rf(), cfg, umbral))
        n_cols = crear_pipeline(RandomForestClassifier(n_estimators=50, random_state=SEED), cfg, umbral).fit(X_train, y_train)
        n_cols = n_cols[:-1].transform(X_train).shape[1]
        filas_sel.append({"Configuración": etiqueta, "Columnas": n_cols,
                          "F1 macro (CV)": round(f1_sel, 4), "Desv.": round(desv_sel, 4)})
    tabla_sel = pd.DataFrame(filas_sel)
    display(tabla_sel)
    elegida = tabla_sel.loc[tabla_sel["F1 macro (CV)"].idxmax(), "Configuración"]
    sel_elegida = opciones[elegida]
    print("Configuración elegida:", elegida)

    mk = lambda clf: crear_pipeline(clf, cfg, sel_elegida)

    # ---------- referencia: métodos de los autores
    registrar(nombre, "Regresión logística", "Autores", mk(LogisticRegression(max_iter=3000, random_state=SEED)))
    registrar(nombre, "Árbol de decisión", "Autores", mk(DecisionTreeClassifier(criterion="entropy", min_samples_leaf=2, random_state=SEED)))
    registrar(nombre, "Naive Bayes", "Autores", mk(GaussianNB()))
    registrar(nombre, "Random Forest", "Autores", mk(RandomForestClassifier(n_estimators=300, random_state=SEED, n_jobs=-1)))
    registrar(nombre, "SVM", "Autores", mk(SVC(random_state=SEED)))
    registrar(nombre, "MLP", "Autores", mk(MLPClassifier(hidden_layer_sizes=(64,), max_iter=500, early_stopping=True, random_state=SEED)))

    # ---------- propuestos sin ajustar
    registrar(nombre, "KNN (sin ajustar)", "Propuesto", mk(KNeighborsClassifier()))
    registrar(nombre, "XGBoost (sin ajustar)", "Propuesto", mk(nuevo_xgb()))

    # ---------- propuestos con Optuna, oprtuna unicamente sobre el ganador de los 3 seleccionados
    est_knn = optimizar(sugerir_knn, lambda p: mk(KNeighborsClassifier(**p)))
    print("KNN  | mejor F1 macro (CV):", round(est_knn.best_value, 4), "|", est_knn.best_params)
    graficar_optuna(est_knn, f"Optuna - KNN ({nombre})")
    registrar(nombre, "KNN (Optuna)", "Propuesto", mk(KNeighborsClassifier(**est_knn.best_params)))

    est_xgb = optimizar(sugerir_xgb, lambda p: mk(nuevo_xgb(**p)))
    print("XGB  | mejor F1 macro (CV):", round(est_xgb.best_value, 4), "|", est_xgb.best_params)
    graficar_optuna(est_xgb, f"Optuna - XGBoost ({nombre})")
    try:
        imp_hp = optuna.importance.get_param_importances(est_xgb)
        print("Importancia de hiperparámetros (XGBoost):", {k: round(v, 3) for k, v in imp_hp.items()})
    except Exception as e:
        print("No se pudo calcular la importancia de hiperparámetros:", e)
    registrar(nombre, "XGBoost (Optuna)", "Propuesto", mk(nuevo_xgb(**est_xgb.best_params)))

    return {"knn": est_knn, "xgb": est_xgb}

