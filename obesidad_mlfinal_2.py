from sklearn.pipeline import Pipeline
from sklearn.compose import ColumnTransformer
from sklearn.preprocessing import StandardScaler, OneHotEncoder, OrdinalEncoder
from sklearn.feature_selection import SelectFromModel
from sklearn.ensemble import RandomForestClassifier
from sklearn.metrics import accuracy_score, f1_score, recall_score, confusion_matrix, classification_report

ORD_CATS = [["no", "Sometimes", "Frequently", "Always"]] * len(ordinales)

def construir_cfg(excluir=()):
    return {"num": [c for c in numericas if c not in excluir]}

def filtro_correlacion(num, umbral=0.90):
    corr = X_train[num].corr().abs()
    sup = corr.where(np.triu(np.ones(corr.shape), k=1).astype(bool))
    return [c for c in sup.columns if (sup[c] > umbral).any()]

def crear_preprocesador(cfg):
    return ColumnTransformer([
        ("num", StandardScaler(), cfg["num"]),
        ("bin", OneHotEncoder(drop="if_binary", sparse_output=False), binarias),
        ("ord", Pipeline([("o", OrdinalEncoder(categories=ORD_CATS, handle_unknown="use_encoded_value", unknown_value=-1)),
                          ("s", StandardScaler())]), ordinales),
        ("nom", OneHotEncoder(handle_unknown="ignore", sparse_output=False), nominales),
    ])

def crear_pipeline(clf, cfg, seleccion):
    """seleccion: None (sin selección) o el umbral de SelectFromModel, p. ej. 'median' o '0.5*median'."""
    pasos = [("prep", crear_preprocesador(cfg))]
    if seleccion:
        pasos.append(("sel", SelectFromModel(
            RandomForestClassifier(n_estimators=100, random_state=SEED, n_jobs=-1), threshold=seleccion)))
    pasos.append(("clf", clf))
    return Pipeline(pasos)

def cv_f1(pipe, cv=cv5):
    r = cross_val_score(pipe, X_train, y_train, cv=cv, scoring="f1_macro", n_jobs=-1)
    return r.mean(), r.std()

resultados = []       # una fila por modelo y escenario (tabla final)
predicciones = {}     # para matrices de confusión

def registrar(escenario, nombre, origen, pipe):
    """Ajusta con TODO el entrenamiento y evalúa UNA vez en prueba."""
    f1_cv, _ = cv_f1(pipe)
    pipe.fit(X_train, y_train)
    pred = pipe.predict(X_test)
    errores = pred != y_test
    adyacentes = (np.abs(pred.astype(int) - y_test.astype(int)) == 1) & errores
    fila = {
        "Escenario": escenario, "Modelo": nombre, "Origen": origen,
        "F1 macro (CV)": round(f1_cv, 4),
        "Accuracy (prueba)": round(accuracy_score(y_test, pred), 4),
        "F1 macro (prueba)": round(f1_score(y_test, pred, average="macro"), 4),
        "Recall macro (prueba)": round(recall_score(y_test, pred, average="macro"), 4),
        "% errores a clase vecina": round(adyacentes.sum() / max(errores.sum(), 1) * 100, 1),
    }
    predicciones[(escenario, nombre)] = pred
    resultados.append(fila)
    return pipe

